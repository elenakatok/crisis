// ═══════════════════════════════════════════════════════════════════════════════
// THE BUILD STAMP. Writes `functions/src/buildInfo.ts` immediately before every
// `tsc`, so the compiled functions carry the commit they were built from.
//
// ⚠⚠ WHY THIS EXISTS. A deployed Cloud Function answers identically whichever
// build is behind it. On 08-08 a KC fix was deployed and there was NO WAY to
// confirm it from outside: `health` returned `{ok, game}`, the callables returned
// their usual 400, and the response headers carried nothing. "Is this version
// live?" was an unanswerable question about production. It is now one curl.
//
// ⚠ `dirty` IS THE POINT, not decoration. It is true when `functions/` has
// uncommitted or untracked changes — i.e. when the deploy has NO COMMIT TO ROLL
// BACK TO. That is the standing rule of this project ("commit before deploying;
// deploying from the working tree leaves nothing to roll back to"), and this makes
// a violation visible in production instead of only in someone's memory.
//
// ⚠ SCOPED TO `functions/`, deliberately. This stamp describes the FUNCTIONS
// artifact. A dirty frontend says nothing about whether the deployed server code
// is reproducible, and folding it in would make `dirty` true so often that it
// would stop meaning anything.
//
// ⚠ IT MUST NEVER FAIL THE BUILD. A missing git, a tarball with no history, a CI
// checkout without `.git` — all produce `commit: 'unknown'` and a successful
// build. A build stamp that can break a deploy is worse than no build stamp.
//
// ⚠ THE OUTPUT IS GENERATED AND GITIGNORED. `builtAt` changes on every build, so
// committing it would mean permanent churn and a stamp that lies about which
// commit produced it. Nothing but the health handler imports it, and no test does,
// so its absence in a fresh clone cannot break anything before the first build.
// ═══════════════════════════════════════════════════════════════════════════════

import { execFileSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const here = path.dirname(fileURLToPath(import.meta.url))
const functionsDir = path.resolve(here, '..')
const repoRoot = path.resolve(functionsDir, '..')

/** Run git in THIS repo, returning '' on any failure. `-C` matters: this is a
 *  multi-repo workspace and the cwd is not a reliable guide to which repo we are in. */
function git(...args) {
  try {
    return execFileSync('git', ['-C', repoRoot, ...args], {
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'ignore'],
    }).trim()
  } catch {
    return ''
  }
}

const commit = git('rev-parse', '--short', 'HEAD') || 'unknown'
// `-- functions` scopes it; untracked files count because an untracked file under
// functions/src IS compiled into the deploy and has no commit behind it.
const dirty = commit !== 'unknown' && git('status', '--porcelain', '--', 'functions') !== ''
const builtAt = new Date().toISOString()

const out = path.join(functionsDir, 'src', 'buildInfo.ts')

writeFileSync(out, `/**
 * ⚠ GENERATED BY scripts/gen-build-info.mjs — DO NOT EDIT, DO NOT COMMIT.
 * Rewritten on every \`npm run build\`. See that script's header for why it exists.
 */

/** What the health endpoint reports about the build behind it. */
export function buildStamp() {
  return {
    /** Short sha of the commit this was built from, or 'unknown' with no git. */
    commit: ${JSON.stringify(commit)},
    /** ⚠ True ⇒ built from an uncommitted functions/ tree: NOTHING TO ROLL BACK TO. */
    dirty: ${dirty},
    builtAt: ${JSON.stringify(builtAt)},
    /**
     * Set by Cloud Run for gen2 functions and INCREMENTED ON EVERY DEPLOY, so it
     * corroborates \`commit\` without depending on the generator having run —
     * a revision that did not change means the deploy did not land. Null locally.
     */
    revision: process.env.K_REVISION ?? null,
  } as const
}
`)

console.log(`[build-info] ${path.basename(repoRoot)}: ${commit}${dirty ? ' (DIRTY)' : ''}`)
